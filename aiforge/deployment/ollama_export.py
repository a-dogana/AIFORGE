import os
import shutil
import subprocess
from typing import Dict, Any, Optional
from aiforge.experiments.registry import ExperimentRegistry

class OllamaExporter:
    """Exports AIFORGE models into Ollama-compatible Modelfiles."""
    
    def __init__(self, registry: ExperimentRegistry):
        self.registry = registry

    def export(self, experiment_id: str, ollama_model_name: Optional[str] = None, system_prompt: Optional[str] = None) -> Dict[str, Any]:
        rec = self.registry.get_experiment_record(experiment_id)
        if not rec:
            raise ValueError(f"Experiment {experiment_id} not found in registry.")

        cfg = rec.get("config", {})
        arch_type = cfg.get("architecture", {}).get("type", "")
        if arch_type != "llm":
            raise ValueError(f"Only LLM models can be exported to Ollama (found '{arch_type}').")

        checkpoint_path = rec.get("checkpoint_path", "")
        if not os.path.exists(checkpoint_path):
            raise FileNotFoundError(f"Checkpoint directory {checkpoint_path} does not exist.")

        name = ollama_model_name or f"aiforge-{experiment_id.lower().replace('_', '-')}"
        sys_prompt = system_prompt or f"You are a specialized model trained and merged with AIFORGE ({rec.get('experiment_name', 'LLM')})."

        modelfile_content = f"""# Auto-generated by AIFORGE v1.6 Ollama Exporter
FROM {os.path.abspath(checkpoint_path)}

PARAMETER temperature 0.7
PARAMETER top_p 0.9
PARAMETER num_ctx 2048

SYSTEM \"\"\"{sys_prompt}\"\"\"
"""
        modelfile_path = os.path.join(checkpoint_path, "Modelfile")
        with open(modelfile_path, "w") as f:
            f.write(modelfile_content)

        # Check if ollama CLI is available on host
        ollama_bin = shutil.which("ollama")
        installed_in_ollama = False
        cli_command = f"ollama create {name} -f '{modelfile_path}'"

        return {
            "status": "success",
            "experiment_id": experiment_id,
            "ollama_model_name": name,
            "modelfile_path": modelfile_path,
            "ollama_available": ollama_bin is not None,
            "create_command": cli_command,
            "modelfile_content": modelfile_content
        }
